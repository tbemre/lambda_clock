import cocotb
from cocotb.clock import Clock
from cocotb.triggers import ClockCycles


@cocotb.test()
async def test_project(dut):
    dut._log.info("Start")

    # Set the clock period to 10 us (100 KHz)
    clock = Clock(dut.clk, 10, unit="us")
    cocotb.start_soon(clock.start())

    # Reset
    dut._log.info("Reset")
    dut.ena.value = 1
    dut.ui_in.value = 0
    dut.uio_in.value = 0
    dut.rst_n.value = 0
    await ClockCycles(dut.clk, 10)
    dut.rst_n.value = 1

    dut._log.info("Test project behavior")

    # Clear inputs (ensure Reset is high, meaning NOT resetting)
    dut.ui_in.value = 0
    dut.uio_in.value = 0

    # Wait for 100 clock cycles to ensure Lambda Clock engine simulates without crashing
    await ClockCycles(dut.clk, 100)

    dut._log.info("Lambda Clock simulated successfully for 100 ticks!")
